#!/usr/bin/env python3
"""Check current Q/A evidence mappings without turning partial support into full proof."""
import argparse
import json
import pathlib
import re

from verification_catalogue import CFG, configuration_claims, target_recipes
from verification_witnesses import load_cases, check_inventory

REPO = pathlib.Path(__file__).resolve().parents[1]
MANIFEST = REPO / "verification/requirements.json"
OUTPUT = REPO / "verification/REQUIREMENTS.md"


def validate(document, design=None):
    if document.get("schema") != 1:
        raise ValueError("unsupported requirement manifest schema")
    design = design if design is not None else (REPO / "docs/DESIGN.md").read_text()
    ids = set(re.findall(r"^\| (Q\d+|A\d+) \|", design, re.M))
    records = document["requirements"]
    found = [row["id"] for row in records]
    if len(found) != len(set(found)) or set(found) != ids:
        raise ValueError(f"requirement inventory differs from DESIGN: {sorted(ids ^ set(found))}")
    witnesses = load_cases()
    check_inventory(witnesses)
    witnessed = {case["module"] for case in witnesses["cases"]}
    modules_for_config = {case["config"]: case["module"] for case in witnesses["cases"]}
    positive = set(CFG.findall(target_recipes((REPO / "Makefile").read_text())["verify-model-all"]))
    for row in records:
        if row["status"] not in {"partial", "external", "constraint"}:
            raise ValueError(f"unsupported coverage claim for {row['id']}: no whole-implementation proof exists")
        if not row["scope"].strip() or not row["remaining"].strip() or not row["bridges"]:
            raise ValueError(f"empty scope, bridge or boundary for {row['id']}")
        if row["status"] == "partial" and not row["formal"]:
            raise ValueError(f"partial formal support needs a checked claim: {row['id']}")
        for evidence in row["formal"]:
            module, config, claim = evidence["module"], evidence["config"], evidence["claim"]
            if module not in witnessed or config not in positive or modules_for_config.get(config) != module:
                raise ValueError(f"unchecked evidence in {row['id']}: {module}/{config}")
            text = (REPO / "verification/tla" / config).read_text()
            if claim not in configuration_claims(text, "INVARIANTS") | configuration_claims(text, "PROPERTIES"):
                raise ValueError(f"{config} does not check {claim} ({row['id']})")
            source = (REPO / "verification/tla" / (module + ".tla")).read_text()
            if not re.search(rf"^{re.escape(claim)}\s*==", source, re.M):
                raise ValueError(f"{module} does not define {claim}")
        for bridge in row["bridges"]:
            path = pathlib.PurePosixPath(bridge["path"])
            if path.is_absolute() or ".." in path.parts or not (REPO / path).is_file():
                raise ValueError(f"missing/unsafe bridge path: {path}")
            if bridge["kind"] not in {"test", "evaluation", "constraint"}:
                raise ValueError(f"unknown bridge kind: {path}")
            symbol = bridge.get("symbol")
            if symbol and not re.search(rf"\b(?:fn|def)\s+{re.escape(symbol)}\s*\(", (REPO / path).read_text()):
                raise ValueError(f"missing bridge symbol: {path}::{symbol}")
    return records


def render(records):
    lines = ["# Current requirement-to-evidence inventory", "",
             "Generated by `python3 review/verification_requirements.py --write`; do not edit the table by hand.", "",
             "Every Q1-Q19 and A01-A36 entry is classified, not declared proved. **Partial** means named finite-model",
             "properties plus concrete bridge tests; tests are not refinement proofs. **External** needs empirical",
             "or environmental evidence. **Constraint** is a design/scope decision. No entry asserts full-system",
             "correctness. Every current model also has an executable normal-path witness, but one witness is not",
             "exhaustive action coverage. The checker validates IDs, named claims and source anchors; it does not",
             "prove the semantic correspondence of prose to a model. Historical sandbox material does not support",
             "current host execution.", "",
             "| Requirement | Class | Checked scope and formal evidence | Concrete evidence | Remaining boundary |",
             "|---|---|---|---|---|"]
    for row in records:
        formal = "; ".join(f"`{e['module']}::{e['claim']}` (`{e['config']}`)" for e in row["formal"])
        bridges = "; ".join(f"{e['kind']}: `{e['path']}{'::' + e['symbol'] if e.get('symbol') else ''}`" for e in row["bridges"])
        cells = [row["id"], row["status"], row["scope"] + (" " + formal if formal else ""), bridges, row["remaining"]]
        lines.append("| " + " | ".join(cell.replace("|", "\\|").replace("\n", " ") for cell in cells) + " |")
    lines += ["", "## Explicit outstanding internal proof work", "",
              "- No trace refinement from Rust/SQLite to the TLA+ modules, no full-module state-space composition.",
              "- Actor/command dispatch coverage is not a proof over every daemon method and every identity.",
              "- MCP JSON-RPC correlation, transport reconnection and complete framing remain implementation tests.",
              "- Bootstrap/schema migrations, fork/retention/export composition and automation admission across",
              "  all work states are not completely composed. The new export model checks a read snapshot and publication only.",
              "- Wait diagnosis is based on impossible conditions and available external paths, not a graph-cycle",
              "  detector; absence of a timer is not proof of deadlock. The complete diagnostic implementation is not proved.",
              "- Reviewer usage propagation is still an implementation accounting gap. Model accounting does not fix it.",
              "- The wider central configuration and arbitrary-string capability proofs require separate completed",
              "  evidence. Timeouts, simulation and smaller configurations cannot substitute for them.", ""]
    return "\n".join(lines)


def self_check(document):
    for mutate in [lambda d: d["requirements"].pop(),
                   lambda d: d["requirements"][0].update(status="proved"),
                   lambda d: d["requirements"][0].update(remaining=""),
                   lambda d: d["requirements"][0]["bridges"][0].update(path="missing-evidence.rs"),
                   lambda d: d["requirements"][3]["formal"][0].update(claim="MissingClaim"),
                   lambda d: d["requirements"][3]["formal"][0].update(module="V2Work")]:
        copy = json.loads(json.dumps(document))
        mutate(copy)
        try:
            validate(copy)
        except ValueError:
            continue
        raise AssertionError("an invalid requirement inventory was accepted")
    print("requirement inventory mutation controls passed")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--self-check", action="store_true")
    args = parser.parse_args()
    document = json.loads(MANIFEST.read_text())
    records = validate(document)
    if args.self_check:
        self_check(document)
    generated = render(records)
    if args.write:
        OUTPUT.write_text(generated)
    elif not OUTPUT.exists() or OUTPUT.read_text() != generated:
        raise ValueError("REQUIREMENTS.md is stale; run with --write")
    print(f"{len(records)} current requirements classified; no whole-implementation proof claimed")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError, KeyError) as error:
        print(f"requirement coverage: {error}")
        raise SystemExit(1)
